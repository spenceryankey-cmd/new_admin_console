#!/usr/bin/env node
// Turns catalog/categories.json into the seed migration for the hetzner database.
// Usage: node scripts/generate-catalog-seed.mjs   (writes hetzner/migrations/0002_seed_catalog.sql)
// Codes are derived mechanically from the labels, so nothing is invented: lowercase, ampersands dropped,
// every other run of non letters and digits becomes one underscore.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = JSON.parse(readFileSync(join(root, 'catalog/categories.json'), 'utf8'))

export const slug = (label) =>
  label.toLowerCase().replace(/&/g, ' ').normalize('NFKD').replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '')
const q = (s) => `'${s.replace(/'/g, "''")}'`

const catCodes = new Set()
const taskCodes = new Set()
let cats = ''
let tasks = ''
src.categories.forEach((c, ci) => {
  const code = slug(c.label)
  if (catCodes.has(code)) throw new Error(`Duplicate category code ${code}`)
  catCodes.add(code)
  cats += `  (${q(code)}, ${q(c.label)}, ${ci + 1}),\n`
  c.tasks.forEach((t, ti) => {
    const tcode = `${code}.${slug(t)}`
    if (taskCodes.has(tcode)) throw new Error(`Duplicate task type code ${tcode}`)
    taskCodes.add(tcode)
    tasks += `  (${q(tcode)}, ${q(code)}, ${q(t)}, ${ti + 1}),\n`
  })
})

const out = `-- 0002_seed_catalog.sql (hetzner)
-- GENERATED by scripts/generate-catalog-seed.mjs from catalog/categories.json. Do not edit by hand.
-- Seeds ${catCodes.size} service categories and ${taskCodes.size} task types, exactly as the live site lists them.
-- Nothing here is invented, renamed or merged. The console and the main backend can only read these tables.

begin;

insert into service_category (code, label, sort_order) values
${cats.replace(/,\n$/, '\n')}on conflict (code) do nothing;

insert into task_type (code, category_code, label, sort_order) values
${tasks.replace(/,\n$/, '\n')}on conflict (code) do nothing;

commit;
`
writeFileSync(join(root, 'hetzner/migrations/0002_seed_catalog.sql'), out)
console.log(`categories ${catCodes.size}, task types ${taskCodes.size}`)
