#!/usr/bin/env node
// Generates the two schema dependent Phase 2 migrations from a small JSON file:
//   supabase/migrations/0002b_xpert_status_columns.sql   columns, links, transition function
//   supabase/migrations/0002c_xpert_backfill.sql         existing Xperts, run only after review
// Usage: node scripts/generate-0002b.mjs scripts/xpert-schema.json
// Nothing is run against a database. Read the output, then run it yourself.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outDir = process.argv[3] ?? join(root, 'supabase/migrations')
const file = process.argv[2]
if (!file) {
  console.error('Usage: node scripts/generate-0002b.mjs scripts/xpert-schema.json')
  process.exit(1)
}
const cfg = JSON.parse(readFileSync(file, 'utf8'))

const ident = (v, what) => {
  if (typeof v !== 'string' || !/^[a-z_][a-z0-9_]*$/.test(v)) throw new Error(`${what} must be a plain lowercase identifier, got ${JSON.stringify(v)}`)
  return v
}
const T = ident(cfg.xpertTable, 'xpertTable')
const ID = ident(cfg.idColumn ?? 'id', 'idColumn')
const idType = ['uuid', 'text', 'integer', 'bigint'].includes(cfg.idType) ? cfg.idType : (() => { throw new Error('idType must be uuid, text, integer or bigint') })()
const created = cfg.createdAtColumn ? ident(cfg.createdAtColumn, 'createdAtColumn') : null
const g = cfg.guarantor
if (g) { ident(g.nameColumn, 'guarantor.nameColumn'); ident(g.contactColumn, 'guarantor.contactColumn'); if (g.relationshipColumn) ident(g.relationshipColumn, 'guarantor.relationshipColumn') }
const tk = cfg.tasks
if (tk) {
  ident(tk.table, 'tasks.table'); ident(tk.xpertIdColumn, 'tasks.xpertIdColumn'); ident(tk.statusColumn, 'tasks.statusColumn')
  if (!Array.isArray(tk.completedValues) || tk.completedValues.length === 0) throw new Error('tasks.completedValues must list at least one value')
}
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`

const statuses = "'applied','guarantor_pending','guarantor_confirmed','skill_verification','provisional_active','full_active','under_review','suspended','removed','inactive','blocked_closed'"

const b = `-- 0002b_xpert_status_columns.sql
-- GENERATED by scripts/generate-0002b.mjs. Review before running. NOT APPLIED.
--
-- Adds five NULLABLE or defaulted columns to public.${T} and one function. No
-- existing column is changed, no rows are removed. Existing rows get
-- account_active = true so nobody loses access when this runs; the backfill in
-- 0002c then sets their real status. New rows default to applied, inactive.
--
-- IMPORTANT: this default makes a NEW registration start with
-- account_active = false. That only has effect once the Railway backend checks
-- account_active (see docs/BACKEND_CHANGES.md). Until then it records, not blocks.

begin;

alter table public.${T}
  add column if not exists xpert_status          text,
  add column if not exists account_active        boolean,
  add column if not exists activated_by          uuid references auth.users (id),
  add column if not exists activated_at          timestamptz,
  add column if not exists verification_source   text;

-- Existing Xperts keep their access until 0002c classifies them.
update public.${T} set account_active = true where account_active is null;
update public.${T} set xpert_status = 'provisional_active' where xpert_status is null;

alter table public.${T}
  alter column xpert_status set default 'applied',
  alter column xpert_status set not null,
  alter column account_active set default false,
  alter column account_active set not null,
  add constraint ${T}_xpert_status_check check (xpert_status in (${statuses})),
  add constraint ${T}_verification_source_check check (verification_source is null or verification_source in ('direct_beyondx','coordinator'));

create index if not exists ${T}_xpert_status_idx on public.${T} (xpert_status);

-- Now the new tables can point at the Xpert table. xpert_id was text; it is
-- compared as text so the link works for any id type.
create or replace function public.xpert_id_exists(p_id text) returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select exists (select 1 from public.${T} where ${ID}::text = p_id)
$$;
revoke execute on function public.xpert_id_exists(text) from public, anon, authenticated;

alter table public.guarantor       add constraint guarantor_xpert_exists       check (public.xpert_id_exists(xpert_id)) not valid;
alter table public.skill_evidence  add constraint skill_evidence_xpert_exists  check (public.xpert_id_exists(xpert_id)) not valid;
alter table public.reference_check add constraint reference_check_xpert_exists check (public.xpert_id_exists(xpert_id)) not valid;
alter table public.status_history  add constraint status_history_xpert_exists  check (public.xpert_id_exists(xpert_id)) not valid;

-- The one place a status changes. The API has already decided the move is legal
-- (packages/shared/src/xpertStatus.ts); this function makes it atomic: it locks
-- the row, refuses if the status moved since the screen was loaded, updates the
-- Xpert and writes the history row in one transaction.
create or replace function public.xpert_apply_transition(
  p_xpert_id          text,
  p_expected_from     text,
  p_to                text,
  p_trigger           text,
  p_reason            text,
  p_actor             uuid,
  p_automatic         boolean,
  p_set_active        boolean,
  p_verification_src  text default null
) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  cur text;
  became_active boolean;
begin
  select xpert_status into cur from public.${T} where ${ID}::text = p_xpert_id for update;
  if not found then
    raise exception 'Xpert not found' using errcode = 'P0002';
  end if;
  if cur is distinct from p_expected_from then
    raise exception 'Status changed from % to % since you opened this Xpert. Reload and try again.', p_expected_from, cur
      using errcode = '40001';
  end if;

  became_active := p_set_active is true;

  update public.${T} set
    xpert_status        = p_to,
    account_active      = coalesce(p_set_active, account_active),
    activated_by        = case when became_active then p_actor else activated_by end,
    activated_at        = case when became_active then now() else activated_at end,
    verification_source = coalesce(p_verification_src, verification_source)
  where ${ID}::text = p_xpert_id;

  insert into public.status_history (xpert_id, old_status, new_status, changed_by, automatic, trigger, reason)
  values (p_xpert_id, cur, p_to, p_actor, p_automatic, p_trigger, p_reason);

  insert into public.audit_log (actor_id, actor_email, action, entity_type, entity_id, before, after, reason)
  values (
    p_actor,
    (select sp.email from public.staff_profile sp where sp.user_id = p_actor),
    'xpert.status_change', '${T}', p_xpert_id,
    jsonb_build_object('xpert_status', cur),
    jsonb_build_object('xpert_status', p_to, 'account_active', p_set_active, 'trigger', p_trigger),
    p_reason
  );

  return jsonb_build_object('from', cur, 'to', p_to);
end $$;
revoke execute on function public.xpert_apply_transition(text,text,text,text,text,uuid,boolean,boolean,text) from public, anon, authenticated;

commit;
`

const c = `-- 0002c_xpert_backfill.sql
-- GENERATED by scripts/generate-0002b.mjs. NOT APPLIED. Run only after 0002b and
-- after the project owner has read the preview below and agreed the cutover date.
--
-- STEP 1 (read only): preview who would get which status. Run this block alone.
${tk ? `--   full_active         ${tk.table} has at least one row with ${tk.statusColumn} in (${tk.completedValues.join(', ')})
--   provisional_active  everyone else
-- Clean feedback cannot be checked yet because there is no feedback table until
-- Phase 5, so this uses completed jobs only. Review the list before step 2.
` : `--   provisional_active  everyone (no tasks table was given, so work history cannot be used)
`}
select ${ID}::text as xpert_id,
${tk ? `  case when exists (select 1 from public.${tk.table} t where t.${tk.xpertIdColumn}::text = x.${ID}::text and t.${tk.statusColumn} in (${tk.completedValues.map(lit).join(', ')}))
       then 'full_active' else 'provisional_active' end as proposed_status`
    : `  'provisional_active' as proposed_status`}
from public.${T} x
order by 2, 1;

-- STEP 2 (writes): classify existing Xperts. Existing Xperts keep access.
begin;

with proposed as (
  select ${ID}::text as xpert_id,
${tk ? `    case when exists (select 1 from public.${tk.table} t where t.${tk.xpertIdColumn}::text = x.${ID}::text and t.${tk.statusColumn} in (${tk.completedValues.map(lit).join(', ')}))
         then 'full_active' else 'provisional_active' end as new_status`
    : `    'provisional_active' as new_status`}
  from public.${T} x
  where xpert_status = 'provisional_active'
), changed as (
  update public.${T} x
     set xpert_status = p.new_status, verification_source = coalesce(x.verification_source, 'direct_beyondx')
    from proposed p
   where x.${ID}::text = p.xpert_id and p.new_status <> x.xpert_status
  returning x.${ID}::text as xpert_id, p.new_status
)
insert into public.status_history (xpert_id, old_status, new_status, automatic, trigger, reason)
select xpert_id, 'provisional_active', new_status, true, 'clean_jobs_completed', 'Backfill at cutover from completed work history'
from changed;

insert into public.status_history (xpert_id, old_status, new_status, automatic, trigger, reason)
select ${ID}::text, null, xpert_status, true, null, 'Existing Xpert at cutover'
from public.${T} x
where not exists (select 1 from public.status_history h where h.xpert_id = x.${ID}::text);
${g ? `
-- Move guarantor details already on the Xpert record into the guarantor table.
-- The original columns are left in place.
insert into public.guarantor (xpert_id, name, contact, relationship, named_at, explainer_sent_at, callback_confirmed_at, callback_outcome, change_reason)
select ${ID}::text, x.${g.nameColumn}, x.${g.contactColumn}, ${g.relationshipColumn ? `x.${g.relationshipColumn}` : 'null'},
       ${created ? `x.${created}` : 'now()'}, null, null, null, 'Imported at cutover, not re-verified'
from public.${T} x
where nullif(trim(x.${g.nameColumn}), '') is not null
  and nullif(trim(x.${g.contactColumn}), '') is not null
  and not exists (select 1 from public.guarantor gg where gg.xpert_id = x.${ID}::text);
` : ''}
commit;
`

writeFileSync(join(outDir, '0002b_xpert_status_columns.sql'), b)
writeFileSync(join(outDir, '0002c_xpert_backfill.sql'), c)
console.log('Wrote 0002b and 0002c in ' + outDir + '. Read them, then run in order.')
